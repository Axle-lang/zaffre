#!/usr/bin/env python3
"""embed_fonts.py — the bundled fonts, as Axle source.

    python3 tools/embed_fonts.py           # rewrite src/text/data/*.axle
    python3 tools/embed_fonts.py --check   # fail if a file is not what assets/fonts/*.ttf make

A consumer builds with the Axle compiler and nothing else, so the default faces travel in the
source: each font is its file's bytes packed into little-endian 32-bit words (signed decimals — a
word with the top bit set is not an `i32` literal otherwise), written as a class whose static
functions return the words in chunks. Chunks, because an array literal is a compile-time unit
and a font is seventeen thousand words; a function that assembles them is `words()`.

The fonts are under the SIL Open Font License; the licence files sit beside the sources in
`assets/fonts/`.
"""
import os
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
FONTS = [
    # (file under assets/fonts, module name, class name, what it is)
    ("InstrumentSans-Regular.ttf", "font_sans_regular", "SansRegular", "Instrument Sans Regular"),
    ("InstrumentSans-Bold.ttf", "font_sans_bold", "SansBold", "Instrument Sans Bold"),
]
CHUNK = 1024      # words per function
PER_LINE = 12


def render(src, mod, cls, what):
    data = open(os.path.join(ROOT, "assets", "fonts", src), "rb").read()
    size = len(data)
    padded = data + b"\0" * (-size % 4)
    words = struct.unpack("<%di" % (len(padded) // 4), padded)
    chunks = [words[i:i + CHUNK] for i in range(0, len(words), CHUNK)]
    out = []
    out.append("// %s — %s, as the words of its file." % (mod, what))
    out.append("//")
    out.append("// GENERATED by tools/embed_fonts.py from assets/fonts/%s. Do not edit:" % src)
    out.append("// `embed_fonts.py --check` fails a tree whose words are not that file's. The font is under")
    out.append("// the SIL Open Font License (assets/fonts/*-OFL.txt).")
    out.append("")
    out.append("/** %s: %d bytes, %d words, %d chunks. */" % (what, size, len(words), len(chunks)))
    out.append("pub(crate) class %s {" % cls)
    out.append("    /** Bytes in the font file. */")
    out.append("    pub(crate) static fn bytes() : i32 {")
    out.append("        return %d;" % size)
    out.append("    }")
    out.append("")
    out.append("    /** Words in the file, padded to a whole number of them. */")
    out.append("    pub(crate) static fn count() : i32 {")
    out.append("        return %d;" % len(words))
    out.append("    }")
    out.append("")
    out.append("    /** How many chunks `chunk` answers for. */")
    out.append("    pub(crate) static fn chunks() : i32 {")
    out.append("        return %d;" % len(chunks))
    out.append("    }")
    out.append("")
    out.append("    /** The whole file's words: every chunk, in order. */")
    out.append("    pub(crate) static fn words() : i32[] {")
    out.append("        let out : i32[] = malloc<i32>(%s::count() as i64);" % cls)
    out.append("        let mut at : i64 = 0;")
    out.append("        for (c of 0..%s::chunks()) {" % cls)
    out.append("            let part : i32[] = %s::chunk(c);" % cls)
    out.append("            for (i of 0..part.length) {")
    out.append("                out[at] = part[i];")
    out.append("                at = at + 1;")
    out.append("            }")
    out.append("        }")
    out.append("        return out;")
    out.append("    }")
    out.append("")
    out.append("    /** Chunk `n` of the words. */")
    out.append("    pub(crate) static fn chunk(n : i32) : i32[] {")
    out.append("        return match n {")
    for k in range(len(chunks)):
        out.append("            %d => %s::c%d()," % (k, cls, k))
    out.append("            _ => %s::c0()," % cls)
    out.append("        };")
    out.append("    }")
    for k, ch in enumerate(chunks):
        out.append("")
        out.append("    pub(file) static fn c%d() : i32[] {" % k)
        out.append("        return [")
        for i in range(0, len(ch), PER_LINE):
            row = ", ".join(str(w) for w in ch[i:i + PER_LINE])
            out.append("            %s%s" % (row, "," if i + PER_LINE < len(ch) else ""))
        out.append("        ];")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    bad = 0
    for src, mod, cls, what in FONTS:
        path = os.path.join(ROOT, "src", "text", "data", mod + ".axle")
        text = render(src, mod, cls, what)
        if "--check" in sys.argv:
            have = open(path).read() if os.path.exists(path) else None
            if have != text:
                sys.stderr.write("embed_fonts: %s is not what %s makes\n" % (path, src))
                bad = 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
            print("wrote", os.path.relpath(path, ROOT))
    sys.exit(bad)


main()
