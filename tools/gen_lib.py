#!/usr/bin/env python3
"""gen_lib.py — src/lib.axle, the wiring header.

    python3 tools/gen_lib.py           # rewrite src/lib.axle
    python3 tools/gen_lib.py --check   # fail if a module is missing from it

The build pulls a module into the compilation unit only if something names it, and the library's
public names (`zaffre::Button`) are the ones its root imports. So the root names every module, one
`use` per directory, bottom layer first — which is also the order doc/ARCHITECTURE.md lists them in.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "src")
LAYERS = ["gfx", "text", "style", "paint", "core", "widgets", "shell"]

HEADER = """// zaffre — a native UI library for Axle, built on smalt and nothing else.
//
// This file is the crate's wiring header: it names every module so the build pulls the whole tree
// into the compilation unit, and so the library's public names are the ones a program imports
// from `zaffre`. It carries no logic and is GENERATED by `tools/gen_lib.py` — `--check` fails a
// tree where a module is missing from it.
//
// Layers, bottom to top — a module never reaches upward (doc/ARCHITECTURE.md, tools/check.py):
//
//   gfx      colour, distance-field shapes, the canvas, the coverage rasteriser
//   text     TrueType, kerning, the glyph cache, fonts, typesetting, string editing
//   style    tokens, themes, style records, easing
//   paint    the `Painter` a widget draws with, and the CPU painter behind it
//   core     geometry, events, models, the context, the `Widget` contract, the `View`
//   widgets  layout containers and the components, atoms upward
//   shell    the window loop over smalt
//
// NOT ONE `use` BELOW NAMES AN OPERATING SYSTEM, and that is checked: `extern "C"` appears nowhere
// in this tree. Everything that touches the machine is smalt's.

"""


def modules():
    out = {}
    for layer in LAYERS:
        d = os.path.join(SRC, layer)
        names = []
        for dp, _, files in os.walk(d):
            for f in sorted(files):
                if f.endswith(".axle"):
                    rel = os.path.relpath(os.path.join(dp, f), SRC)[:-5].split(os.sep)
                    names.append(rel)
        out[layer] = sorted(names)
    return out


def render():
    lines = []
    for layer, mods in modules().items():
        by = {}
        for m in mods:
            by.setdefault("::".join(m[:-1]), []).append(m[-1])
        for prefix, names in sorted(by.items()):
            lines.append("use crate::%s::{%s};" % (prefix, ", ".join(names)))
        lines.append("")
    return HEADER + "\n".join(lines).rstrip() + "\n"


def main():
    path = os.path.join(SRC, "lib.axle")
    text = render()
    if "--check" in sys.argv:
        have = open(path).read() if os.path.exists(path) else ""
        if have != text:
            sys.stderr.write("gen_lib: src/lib.axle is not what the tree makes\n")
            sys.exit(1)
        return
    open(path, "w").write(text)
    print("wrote src/lib.axle")


main()
